package config

import (
	"fmt"
	"io"
	"reflect"
	"strings"
)

// Document writes the configuration reference as a Markdown table, derived
// from the struct tags. Secret fields never show a default.
func Document(w io.Writer) error {
	var cfg Config
	var b strings.Builder
	b.WriteString("# Configuration reference\n\n")
	b.WriteString("Generated by `go run ./shared/config/cmd/configdoc`; do not edit by hand.\n\n")
	b.WriteString("Precedence, lowest to highest: default, JSON file named by `IAM_CONFIG_FILE`, environment.\n")
	b.WriteString("File keys are the lower-case variable names without the `IAM_` prefix.\n\n")
	b.WriteString("| Variable | File key | Type | Default | Required | Description |\n")
	b.WriteString("|---|---|---|---|---|---|\n")
	for _, f := range fieldsOf(reflect.ValueOf(&cfg).Elem()) {
		def := "-"
		if f.def != "" && !f.secret {
			def = "`" + f.def + "`"
		}
		key := "`" + f.key + "`"
		if f.nofile {
			key = "-"
		}
		req := "no"
		if f.required {
			req = "yes"
		}
		secret := ""
		if f.secret {
			secret = " Secret."
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s%s |\n", f.env, key, f.typeName, def, req, strings.ReplaceAll(f.doc, "|", "\\|"), secret)
	}
	_, err := io.WriteString(w, b.String())
	return err
}
